export type LabId = (typeof labExperiments)[number]["id"];
export type LabResult = {
  id: string;
  type: LabId;
  timestamp: number;
  protocol: 1;
  values: number[];
  score: number;
  errors: number;
};
export function validLabResult(r: unknown): r is LabResult {
  if (!r || typeof r !== "object") return false;
  const v = r as LabResult;
  return (
    typeof v.id === "string" &&
    labExperiments.some((x) => x.id === v.type) &&
    v.protocol === 1 &&
    Number.isFinite(v.timestamp) &&
    Number.isFinite(v.score) &&
    Number.isFinite(v.errors) &&
    Array.isArray(v.values) &&
    v.values.length === 5 &&
    v.values.every(Number.isFinite)
  );
}
export function probabilityTrial(round: number, rng = Math.random) {
  const p = 10 + Math.floor(rng() * 8) * 10,
    prize = 20 + Math.floor(rng() * 12) * 10,
    ev = (p * prize) / 100;
  const gap = [20, 12, 7, 4, 2][round];
  const other = Math.max(1, Math.round(ev + (rng() > 0.5 ? gap : -gap)));
  const choices = shuffled(
    [
      { label: `${p}% chance of ${prize} points`, value: ev },
      { label: `Guaranteed ${other} points`, value: other },
    ],
    rng,
  );
  return { choices, correct: choices[0].value > choices[1].value ? 0 : 1 };
}
export function randomnessTrial(rng = Math.random) {
  const patterns = ["01", "0011", "000111", "010011", "00101101"];
  const motif = patterns[Math.floor(rng() * patterns.length)];
  const offset = Math.floor(rng() * motif.length);
  const patterned = Array.from({ length: 24 }, (_, i) =>
    motif[(i + offset) % motif.length] === "1" ? "●" : "○",
  ).join(" ");
  let random = "";
  for (let i = 0; i < 100; i++) {
    random = Array.from({ length: 24 }, () => (rng() < 0.5 ? "●" : "○")).join(
      " ",
    );
    if (random !== patterned) break;
  }
  const correct = rng() < 0.5 ? 0 : 1;
  return {
    choices: correct === 0 ? [random, patterned] : [patterned, random],
    correct,
  };
}
export type Dot = { x: number; y: number; vx: number; vy: number };
export function dotPositions(count: number, rng = Math.random): Dot[] {
  return Array.from({ length: count }, (_, i) => ({
    x: 12 + (i % 4) * 25,
    y: 18 + Math.floor(i / 4) * 30,
    vx: (rng() > 0.5 ? 1 : -1) * (9 + rng() * 9),
    vy: (rng() > 0.5 ? 1 : -1) * (9 + rng() * 9),
  }));
}
export function moveDots(dots: Dot[], dt: number): Dot[] {
  return dots.map((d) => {
    let x = d.x + d.vx * dt,
      y = d.y + d.vy * dt,
      vx = d.vx,
      vy = d.vy;
    if (x < 5 || x > 95) {
      vx = -vx;
      x = Math.max(5, Math.min(95, x));
    }
    if (y < 7 || y > 93) {
      vy = -vy;
      y = Math.max(7, Math.min(93, y));
    }
    return { x, y, vx, vy };
  });
}
